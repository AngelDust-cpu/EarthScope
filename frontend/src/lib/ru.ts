export function variableLabel(variable: Variable): string {
  return ru.variable[variable]
}

export function unitLabel(unit: string): string {
  if (unit === '°C' || unit === 'C') return ru.unit.celsius
  if (unit === 'mm') return ru.unit.precipitation
  if (unit === 'mm/day') return ru.unit.dailyPrecipitation
  return unit
}

export function displayError(error: Error): string {
  if (error instanceof ApiError && Object.hasOwn(ru.error, error.code)) {
    return ru.error[error.code as keyof typeof ru.error]
  }
  return ru.error.unavailable
}
